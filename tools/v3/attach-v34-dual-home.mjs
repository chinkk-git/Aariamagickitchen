import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const [input, output] = process.argv.slice(2);
if (!input || !output) throw new Error('Usage: node tools/v3/attach-v34-dual-home.mjs <transformed-html> <output-html>');
const source = fs.readFileSync(path.resolve(input), 'utf8');
const adapterTemplate = fs.readFileSync(path.join(root, 'tools/v3/v34-dual-home.js'), 'utf8');
const welcomeArtwork = fs.readFileSync(path.join(root, 'docs/design/v3.4/Aaria_Welcome_Final_Enter_Arrow.png'));
const isJpeg = welcomeArtwork[0] === 0xff && welcomeArtwork[1] === 0xd8;
const isPng = welcomeArtwork.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
if (!isJpeg && !isPng) throw new Error('Approved V3.4 welcome artwork has an unsupported image signature.');
const welcomeMime = isJpeg ? 'image/jpeg' : 'image/png';
const welcomeDataUri = 'data:' + welcomeMime + ';base64,' + welcomeArtwork.toString('base64');
if (adapterTemplate.includes('__V34_WELCOME_ART_DATA_URI__')) throw new Error('The welcome artwork must use the shared first-paint CSS variable.');
const marker = '<script id="aaria-v3-layer">';
const start = source.indexOf(marker);
const close = source.indexOf('</script>', start);
const headClose = source.toLowerCase().indexOf('</head>');
const bodyOpen = source.match(/<body\b[^>]*>/i);
if (start < 0 || close < 0 || source.indexOf(marker, start + 1) >= 0) throw new Error('Expected exactly one complete shared V3 runtime script.');
if (headClose < 0 || !bodyOpen) throw new Error('Expected a head and body for the first-paint welcome shell.');
const bootStyle = '<style id="v34-welcome-boot-style">:root{--v34-welcome-art:url(' + JSON.stringify(welcomeDataUri) + ')}html,body{background:#35114e!important}#v34-welcome-boot{position:fixed;z-index:2147483647;inset:0;display:grid;place-items:center;overflow:hidden;padding:max(8px,env(safe-area-inset-top)) max(12px,env(safe-area-inset-right)) max(10px,env(safe-area-inset-bottom)) max(12px,env(safe-area-inset-left));background:radial-gradient(ellipse at 50% 43%,#7d45a9,#35114e 78%)}#v34-welcome-boot-frame{height:calc(100dvh - 40px);max-height:100%;max-width:100%;aspect-ratio:.4921875/1;border-radius:16px;background-image:var(--v34-welcome-art);background-repeat:no-repeat;background-size:303% 100%;background-position:0 center;box-shadow:0 12px 30px #1d0a2e80}</style>';
let result = source.slice(0, headClose) + bootStyle + source.slice(headClose);
const updatedBody = result.match(/<body\b[^>]*>/i);
const bodyAt = updatedBody.index + updatedBody[0].length;
result = result.slice(0, bodyAt) + '<div id="v34-welcome-boot" aria-hidden="true"><div id="v34-welcome-boot-frame"></div></div>' + result.slice(bodyAt);
const updatedMarker = result.indexOf(marker);
const updatedClose = result.indexOf('</script>', updatedMarker);
result = result.slice(0, updatedClose) + '\n' + adapterTemplate + '\n' + result.slice(updatedClose);
if (!result.includes('aaria.v34.homeStyle') || !result.includes('Magical Adventure') || !result.includes('v34-welcome-enter') || !result.includes('id="v34-welcome-boot"') || result.indexOf('id="v34-welcome-boot"') > result.indexOf(marker)) throw new Error('V3.4 welcome boot shell or adapter was not attached before the app runtime.');
fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
fs.writeFileSync(path.resolve(output), result);
console.log(`Attached V3.4 APK-only home adapter to ${output} (${result.length.toLocaleString()} chars).`);
